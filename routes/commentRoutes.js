const express = require("express");

const {
  createComment,
  getComments,
  deleteComment,
  likeComment,
  unlikeComment,
} = require("../controllers/commentController");

const protect = require("../middleware/authMiddleware");

const router = express.Router();

/*
|--------------------------------------------------------------------------
| CREATE COMMENT
|--------------------------------------------------------------------------
| POST /api/comments/post/:postId
|--------------------------------------------------------------------------
| Login required
|--------------------------------------------------------------------------
*/
router.post(
  "/post/:postId",
  protect,
  createComment
);

/*
|--------------------------------------------------------------------------
| GET COMMENTS
|--------------------------------------------------------------------------
| GET /api/comments/post/:postId
|--------------------------------------------------------------------------
| Public route
|--------------------------------------------------------------------------
*/
router.get(
  "/post/:postId",
  getComments
);

/*
|--------------------------------------------------------------------------
| DELETE COMMENT
|--------------------------------------------------------------------------
| DELETE /api/comments/:id
|--------------------------------------------------------------------------
| Login required
|--------------------------------------------------------------------------
*/
router.delete(
  "/:id",
  protect,
  deleteComment
);

/*
|--------------------------------------------------------------------------
| LIKE COMMENT
|--------------------------------------------------------------------------
| POST /api/comments/:id/like
|--------------------------------------------------------------------------
| Login required
|--------------------------------------------------------------------------
*/
router.post(
  "/:id/like",
  protect,
  likeComment
);

/*
|--------------------------------------------------------------------------
| UNLIKE COMMENT
|--------------------------------------------------------------------------
| DELETE /api/comments/:id/like
|--------------------------------------------------------------------------
| Login required
|--------------------------------------------------------------------------
*/
router.delete(
  "/:id/like",
  protect,
  unlikeComment
);

module.exports = router;
const express = require("express");

const {
  createPost,
  getPosts,
  getPostById,
  deletePost,
  likePost,
  unlikePost,
  savePost,
  unsavePost,
} = require("../controllers/postController");

const protect = require("../middleware/authMiddleware");

const router = express.Router();

/*
|--------------------------------------------------------------------------
| PUBLIC POST ROUTES
|--------------------------------------------------------------------------
*/

/*
|--------------------------------------------------------------------------
| Get All Posts
|--------------------------------------------------------------------------
| GET /api/posts
|--------------------------------------------------------------------------
| No login required.
|--------------------------------------------------------------------------
*/

router.get("/", getPosts);

/*
|--------------------------------------------------------------------------
| Get Single Post
|--------------------------------------------------------------------------
| GET /api/posts/:id
|--------------------------------------------------------------------------
| No login required.
|--------------------------------------------------------------------------
*/

router.get("/:id", getPostById);

/*
|--------------------------------------------------------------------------
| PROTECTED POST ROUTES
|--------------------------------------------------------------------------
*/

/*
|--------------------------------------------------------------------------
| Create Post
|--------------------------------------------------------------------------
| POST /api/posts
|--------------------------------------------------------------------------
*/

router.post(
  "/",
  protect,
  createPost
);

/*
|--------------------------------------------------------------------------
| Like Post
|--------------------------------------------------------------------------
| POST /api/posts/:id/like
|--------------------------------------------------------------------------
*/

router.post(
  "/:id/like",
  protect,
  likePost
);

/*
|--------------------------------------------------------------------------
| Unlike Post
|--------------------------------------------------------------------------
| DELETE /api/posts/:id/like
|--------------------------------------------------------------------------
*/

router.delete(
  "/:id/like",
  protect,
  unlikePost
);

/*
|--------------------------------------------------------------------------
| Save Post
|--------------------------------------------------------------------------
| POST /api/posts/:id/save
|--------------------------------------------------------------------------
*/

router.post(
  "/:id/save",
  protect,
  savePost
);

/*
|--------------------------------------------------------------------------
| Unsave Post
|--------------------------------------------------------------------------
| DELETE /api/posts/:id/save
|--------------------------------------------------------------------------
*/

router.delete(
  "/:id/save",
  protect,
  unsavePost
);

/*
|--------------------------------------------------------------------------
| Delete Post
|--------------------------------------------------------------------------
| DELETE /api/posts/:id
|--------------------------------------------------------------------------
| Only the post owner can delete it.
|--------------------------------------------------------------------------
*/

router.delete(
  "/:id",
  protect,
  deletePost
);

/*
|--------------------------------------------------------------------------
| Export Router
|--------------------------------------------------------------------------
*/

module.exports = router;